// Regenerates src/shared/motion-templates/fonts.ts from the .woff2 files beside it.
//
// Motion pages must not reach the network (preview iframe and export window
// both block it), so their fonts travel INSIDE the page as data URLs. A
// generated module rather than a `?inline` import, because the same string has
// to resolve identically in the renderer, the main process and vitest.
//
// Where each file comes from, and how the subsets were cut: fonts/README.md.
import { readFileSync, readdirSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'shared', 'motion-templates', 'fonts')

/** Arabic script: Persian, Arabic, Urdu letters and digits, the joiners and marks, presentation forms. */
const ARABIC_RANGE = 'U+0600-06FF,U+0750-077F,U+08A0-08FF,U+200C-200F,U+25CC,U+FB50-FDFF,U+FE70-FEFF'
/**
 * The space and the punctuation Persian text uses most, so a stack that names
 * Vazirmatn alone does not borrow them from a system font. Only the Vazirmatn
 * family claims them; inside Inter, Inter keeps its own.
 */
const SPACING_RANGE = 'U+0020-0021,U+0028-0029,U+002C-002E,U+003A,U+00A0,U+00AB,U+00BB,U+2013-2014,U+2026'

const faces = [
	// One variable file per family serves every weight. Templates name
	// 'Outfit, Inter' for headings (board 1) and Inter for everything else.
	{ file: 'Inter-roman-latin.woff2', families: ['Inter'], weight: '100 900' },
	// Outfit's latin subset from Google Fonts (v15), OFL — fonts/OFL-Outfit.txt.
	{ file: 'Outfit-latin.woff2', families: ['Outfit'], weight: '100 900' },
	// Vazirmatn v33.003, Arabic-script subset, OFL — fonts/OFL-Vazirmatn.txt.
	// Also declared INSIDE the Inter family for Arabic-script code points only:
	// every bundled stack ends in Inter, so Persian text in any template or page
	// that names Inter (or 'Outfit, Inter') draws in Vazirmatn with no change to
	// its Latin. Declared after Inter, so the browser checks it first for those
	// characters (CSS Fonts: the last matching face wins).
	{ file: 'Vazirmatn-arabic.woff2', families: ['Vazirmatn'], weight: '100 900', range: `${SPACING_RANGE},${ARABIC_RANGE}` },
	{ file: 'Vazirmatn-arabic.woff2', families: ['Inter'], weight: '100 900', range: ARABIC_RANGE }
]
for (const f of faces) {
	if (!readdirSync(dir).includes(f.file)) throw new Error(`missing ${f.file}`)
}

// Each file's base64 is written ONCE as a constant and the rules are joined at
// load, so a face declared under two family names does not double the module.
const constName = (file) => file.replace(/\.woff2$/, '').replace(/[^A-Za-z0-9]+/g, '_').toUpperCase()
const constants = [...new Map(faces.map((f) => [f.file, f])).values()].map((f) =>
	`const ${constName(f.file)} = ${JSON.stringify(readFileSync(join(dir, f.file)).toString('base64'))}`)
const rules = faces.flatMap((f) => f.families.map((family) => {
	const range = f.range ? `, ${JSON.stringify(f.range)}` : ''
	return `face(${JSON.stringify(family)}, ${constName(f.file)}, ${JSON.stringify(f.weight)}${range})`
}))

const out = [
	'// GENERATED by scripts/embed-motion-fonts.mjs — do not edit by hand.',
	'// Inter is © The Inter Project Authors, SIL Open Font License 1.1 (fonts/OFL.txt).',
	'// Outfit is © 2021 The Outfit Project Authors, SIL Open Font License 1.1 (fonts/OFL-Outfit.txt).',
	'// Vazirmatn is © 2015 The Vazirmatn Project Authors, SIL Open Font License 1.1 (fonts/OFL-Vazirmatn.txt).',
	'',
	...constants,
	'',
	'const face = (family: string, b64: string, weight: string, range?: string) =>',
	'\t`@font-face{font-family:\'${family}\';src:url(data:font/woff2;base64,${b64}) format(\'woff2\');font-weight:${weight};font-style:normal;font-display:block${range ? `;unicode-range:${range}` : \'\'}}`',
	'',
	`/** The families every motion page can name: ${[...new Set(faces.flatMap((f) => f.families))].join(', ')}. */`,
	`export const MOTION_FONT_FAMILIES = ${JSON.stringify([...new Set(faces.flatMap((f) => f.families))])}`,
	'',
	`export const MOTION_FONT_CSS = [\n\t${rules.join(',\n\t')}\n].join('\\n')`,
	''
].join('\n')
writeFileSync(join(dir, '..', 'fonts.ts'), out)
console.log(`fonts.ts: ${(out.length / 1024).toFixed(0)} KB`)
